<script>
document.querySelectorAll('.apply-btn').forEach(btn => {
  btn.addEventListener('click', () => {

    const job = btn.dataset.job;
    const dept = btn.dataset.department;

    const formSection = document.getElementById('apply-form');
    const jobSelect = document.getElementById('jobRole');
    const deptSelect = document.getElementById('department');

    if (!formSection) {
      console.error('Apply form not found');
      return;
    }

    // Scroll with offset (sticky header safe)
    const headerOffset = 120;
    const elementPosition = formSection.getBoundingClientRect().top;
    const offsetPosition = elementPosition + window.pageYOffset - headerOffset;

    window.scrollTo({
      top: offsetPosition,
      behavior: "smooth"
    });

    // Auto select values
    if (jobSelect && deptSelect) {
      setTimeout(() => {
        jobSelect.value = job || "";
        deptSelect.value = dept || "";
      }, 300);
    }

  });
});
</script>



