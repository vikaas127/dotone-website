<script>
let roiPeriod = "monthly";

function setROIPeriod(period) {
    roiPeriod = period;
    document.getElementById("monthlyBtn").classList.remove("active");
    document.getElementById("annualBtn").classList.remove("active");
    document.getElementById(period + "Btn").classList.add("active");
    calculateHRMSROI();
}

function updateGrowthLabel() {
    document.getElementById("growthLabel").innerText =
        document.getElementById("growthRate").value + "%";
}

function calculateHRMSROI() {
    const emp = Number(document.getElementById("empCount").value || 0);
    const growth = Number(document.getElementById("growthRate").value || 0) / 100;
    const hrCost = Number(document.getElementById("hrCost").value || 0);
    const errors = Number(document.getElementById("payrollErrors").value || 0);
    const errorCost = Number(document.getElementById("errorCost").value || 0);

    if (emp === 0 || hrCost === 0) return;

    const futureEmp = emp + (emp * growth);
    const scaleFactor = futureEmp / emp;

    let hrSavings = hrCost * 0.35 * scaleFactor;       // 35% HR efficiency
    let payrollSavings = errors * errorCost * 0.7;     // 70% error reduction

    if (roiPeriod === "annual") {
        hrSavings *= 12;
        payrollSavings *= 12;
    }

    const total = hrSavings + payrollSavings;

    document.getElementById("hrSavings").innerText =
        "₹" + Math.round(hrSavings).toLocaleString();

    document.getElementById("errorSavings").innerText =
        "₹" + Math.round(payrollSavings).toLocaleString();

    document.getElementById("totalROI").innerText =
        "₹" + Math.round(total).toLocaleString();
}
</script>


