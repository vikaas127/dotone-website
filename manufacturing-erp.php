<script>
function calculateManufacturingROI() {
    const production = Number(document.getElementById('roiProduction').value || 0);
    const defectRate = Number(document.getElementById('roiDefectRate').value || 0) / 100;
    const defectCost = Number(document.getElementById('roiDefectCost').value || 0);
    const manpower = Number(document.getElementById('roiManpower').value || 0);
    const downtime = Number(document.getElementById('roiDowntime').value || 0);

    const defectLoss = production * defectRate * defectCost;

    const defectSaving = defectLoss * 0.65;     // Avg 65% defect reduction
    const manpowerSaving = manpower * 0.30;     // Avg 30% manpower optimization
    const downtimeSaving = downtime * 0.40;     // Avg 40% downtime reduction

    const totalROI = defectSaving + manpowerSaving + downtimeSaving;

    document.getElementById('roiDefectSaving').innerText = "₹" + Math.round(defectSaving).toLocaleString();
    document.getElementById('roiManpowerSaving').innerText = "₹" + Math.round(manpowerSaving).toLocaleString();
    document.getElementById('roiDowntimeSaving').innerText = "₹" + Math.round(downtimeSaving).toLocaleString();
    document.getElementById('roiTotal').innerText = "₹" + Math.round(totalROI).toLocaleString();
}
</script>

