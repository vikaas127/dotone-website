<script>
function calculateIndustryROI() {
    const prodValue = Number(document.getElementById("prodValue").value) || 0;
    const downtimeCost = Number(document.getElementById("downtimeCost").value) || 0;
    const scrapCost = Number(document.getElementById("scrapCost").value) || 0;
    const manualOpsCost = Number(document.getElementById("manualOpsCost").value) || 0;

    // Conservative Industry 4.0 assumptions
    const productivityGain = prodValue * 0.05;      // 5% productivity improvement
    const downtimeSavings = downtimeCost * 0.35;    // 35% downtime reduction
    const scrapSavings = scrapCost * 0.4;            // 40% quality improvement
    const manpowerSavings = manualOpsCost * 0.3;     // 30% automation impact

    const totalROI = productivityGain + downtimeSavings + scrapSavings + manpowerSavings;

    document.getElementById("productivityGain").innerText = "₹" + productivityGain.toLocaleString();
    document.getElementById("downtimeSavings").innerText = "₹" + downtimeSavings.toLocaleString();
    document.getElementById("scrapSavings").innerText = "₹" + scrapSavings.toLocaleString();
    document.getElementById("manpowerSavings").innerText = "₹" + manpowerSavings.toLocaleString();
    document.getElementById("totalIndustryROI").innerText = "₹" + totalROI.toLocaleString();
}
</script>

