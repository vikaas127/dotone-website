<script>
function calculateInventoryROI() {
    const inventoryValue = Number(document.getElementById("inventoryValue").value) || 0;
    const carryingCost = Number(document.getElementById("carryingCost").value) || 0;
    const manualCost = Number(document.getElementById("manualCost").value) || 0;
    const stockLoss = Number(document.getElementById("stockLoss").value) || 0;

    // Assumptions
    const carryingSavings = inventoryValue * (carryingCost / 100) * 0.25; // 25% reduction
    const manualSavings = manualCost * 12 * 0.6; // 60% automation reduction
    const lossSavings = stockLoss * 0.4; // 40% loss reduction

    const total = carryingSavings + manualSavings + lossSavings;

    document.getElementById("holdingSavings").innerText = "₹" + carryingSavings.toLocaleString();
    document.getElementById("manualSavings").innerText = "₹" + manualSavings.toLocaleString();
    document.getElementById("lossSavings").innerText = "₹" + lossSavings.toLocaleString();
    document.getElementById("totalROI").innerText = "₹" + total.toLocaleString();
}
</script>

