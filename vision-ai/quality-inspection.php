<!-- ROI Script -->
<script>
function calculateROI() {
    const production = Number(document.getElementById('production').value || 0);
    const defectRate = Number(document.getElementById('defectRate').value || 0) / 100;
    const defectCost = Number(document.getElementById('defectCost').value || 0);
    const manpower = Number(document.getElementById('manpowerCost').value || 0);

    const defectLoss = production * defectRate * defectCost;
    const defectSavings = defectLoss * 0.6; // avg 60% reduction
    const manpowerSavings = manpower * 0.3; // avg 30% optimization
    const totalROI = defectSavings + manpowerSavings;

    document.getElementById('defectSavings').innerText = "₹" + Math.round(defectSavings).toLocaleString();
    document.getElementById('manpowerSavings').innerText = "₹" + Math.round(manpowerSavings).toLocaleString();
    document.getElementById('totalROI').innerText = "₹" + Math.round(totalROI).toLocaleString();
}
</script>

