<script>
(function () {

    const webinarTime = new Date("2026-01-25T16:00:00").getTime();

    function pad(n) {
        return n.toString().padStart(2, '0');
    }

    const timer = setInterval(() => {
        const now = new Date().getTime();
        const diff = webinarTime - now;

        if (diff <= 0) {
            clearInterval(timer);

            // Zero main timer
            ['days','hours','minutes','seconds'].forEach(id => {
                const el = document.getElementById(id);
                if (el) el.innerText = "00";
            });

            // Hide sticky CTA
            const sticky = document.getElementById("stickyCta");
            if (sticky) sticky.style.display = "none";

            // Replace registration section
            const reg = document.getElementById("register");
            if (reg) {
                reg.innerHTML = `
                    <div class="card p-10 text-center">
                        <h2 class="text-3xl font-display font-bold mb-4">
                            Registration closed
                        </h2>
                        <p class="text-text-secondary">
                            This webinar has already started or reached capacity.
                        </p>
                    </div>
                `;
            }

            return;
        }

        const days = Math.floor(diff / (1000 * 60 * 60 * 24));
        const hours = Math.floor((diff / (1000 * 60 * 60)) % 24);
        const minutes = Math.floor((diff / (1000 * 60)) % 60);
        const seconds = Math.floor((diff / 1000) % 60);

        // Main timer
        if (document.getElementById("days")) document.getElementById("days").innerText = pad(days);
        if (document.getElementById("hours")) document.getElementById("hours").innerText = pad(hours);
        if (document.getElementById("minutes")) document.getElementById("minutes").innerText = pad(minutes);
        if (document.getElementById("seconds")) document.getElementById("seconds").innerText = pad(seconds);

        // Mini sticky timer
        if (document.getElementById("miniHours")) {
            document.getElementById("miniHours").innerText = pad(hours);
            document.getElementById("miniMinutes").innerText = pad(minutes);
            document.getElementById("miniSeconds").innerText = pad(seconds);
        }

    }, 1000);

})();
</script>
<script>
function animateNumber(el, start, end, duration = 800) {
    let startTime = null;

    function step(timestamp) {
        if (!startTime) startTime = timestamp;
        const progress = Math.min((timestamp - startTime) / duration, 1);
        el.innerText = Math.floor(progress * (end - start) + start);
        if (progress < 1) requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
}

